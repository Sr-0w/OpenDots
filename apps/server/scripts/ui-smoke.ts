globalThis.fetch = async (input, init) => {
  const url = input instanceof Request ? input.url : String(input);
  if (url.includes('gravatar.com/')) return url.includes('.json') ? Response.json({ entry: [{ name: { givenName: 'Camille', familyName: 'Martin' } }] }) : new Response(avatarBytes, { headers: { 'content-type': 'image/png' } });
  if (url.includes('openrouter.ai/api/v1/models/')) return Response.json({ data: { endpoints: [{ provider_name: 'Fixture' }] } });
  if (url === 'https://openrouter.ai/api/v1/models') return Response.json({ data: [{ id:'fixture/model', name:'Modèle de test', supported_parameters:['tools'], architecture:{input_modalities:['text'],output_modalities:['text']} }] });
  return nativeFetch(input, init);
};

