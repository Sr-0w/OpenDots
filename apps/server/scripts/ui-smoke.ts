/** Browser + real HTTP smoke; no external account or paid API calls. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { serve } from '@hono/node-server';

const dir = await mkdtemp(join(tmpdir(), 'opendots-ui-'));
process.env.OPENDOTS_DATA_DIR = dir;
process.env.OPENDOTS_GOOGLE_CLIENT_ID = 'browser-fixture';
process.env.OPENDOTS_GOOGLE_CLIENT_SECRET = 'browser-fixture-secret';
const { createApplication } = await import('../src/app.ts');
const { authStore, closeAuthStore, accountById, promoteAdmin } = await import('../src/auth/store.ts');
const { withAccount } = await import('../src/auth/context.ts');
const { openDatabase, closeAllDatabases } = await import('../src/db/client.ts');
const { createAgent } = await import('../src/agents/repo.ts');
const { setSetting, setOpenRouterKey } = await import('../src/settings.ts');
const { createConnector, listConnectors } = await import('../src/connectors/repo.ts');
await authStore(true);
const app = createApplication(async () => { await openDatabase({ memory: true }); });
const server = serve({ fetch: app.fetch, port: 0, hostname: '127.0.0.1' });
await new Promise<void>((resolve) => server.listening ? resolve() : server.once('listening', resolve));
const address = server.address() as { port: number };
const origin = `http://127.0.0.1:${address.port}`;
const browser = await chromium.launch({ executablePath: process.env.OPENDOTS_CHROMIUM_PATH || undefined, headless: true, args: ['--no-sandbox'] });
try {
  const context = await browser.newContext({ locale: 'fr-BE', viewport: { width: 1365, height: 1000 } });
  const page = await context.newPage();
  const errors: string[] = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(origin);
  await page.getByRole('heading', { name: 'Connecte-toi à ton espace' }).waitFor();
  await page.getByRole('button', { name: 'Pas encore de compte ? S’inscrire' }).click();
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('browser@example.com');
  await page.getByLabel('Mot de passe', { exact: true }).fill('browser password for test');
  await page.getByLabel('Confirmer le mot de passe').fill('different password');
  await page.getByRole('button', { name: 'Créer mon compte', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Les mots de passe ne correspondent pas.' }).waitFor();
  await page.getByLabel('Confirmer le mot de passe').fill('browser password for test');
  await page.getByRole('button', { name: 'Créer mon compte', exact: true }).click();
  await page.getByText('1. Clé OpenRouter', { exact: true }).waitFor();
  const profile = await (await context.request.get(`${origin}/api/auth/me`)).json();
  const account = (await accountById(profile.account.id))!;
  assert.equal(account.role, 'user');
  // Seed a completed local fixture; this does not claim real key validation.
  await withAccount(account, async () => {
    await setOpenRouterKey('ui-fixture-personal-key');
    await setSetting('onboarding.done', true);
    await setSetting('models.default', { provider: 'openrouter', model: 'fixture/model' });
    await createAgent({ name: 'Ari privé' });
  });
  await page.reload();
  await page.getByRole('button', { name: 'Connecteurs', exact: true }).click();
  for (const name of ['Google Drive', 'Google Calendar', 'Gmail', 'Outlook / Microsoft 365', 'GitHub', 'IMAP / SMTP']) await page.getByRole('heading', { name, exact: true }).waitFor();
  assert.equal(await page.getByText('Applications OAuth du déploiement', { exact: true }).count(), 0);
  assert.equal(await page.getByText('Serveurs MCP', { exact: true }).count(), 0);
  const search = page.getByRole('textbox', { name: 'Rechercher un service' });
  await search.fill('calendar');
  await page.getByRole('heading', { name: 'Google Calendar', exact: true }).waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Gmail', exact: true }).count(), 0);
  await search.fill('');
  const card = page.locator('div.rounded-2xl').filter({ has: page.getByRole('heading', { name: 'Gmail', exact: true }) }).last();
  await card.getByRole('button', { name: 'Connecter', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('heading', { name: 'Connecter Gmail' }).waitFor();
  const checkboxes = dialog.getByRole('checkbox');
  assert.equal(await checkboxes.count(), 3); assert.equal(await checkboxes.nth(0).getAttribute('aria-checked'), 'true');
  assert.equal(await checkboxes.nth(1).getAttribute('aria-checked'), 'false');
  await checkboxes.nth(1).click();
  await context.route('https://accounts.google.com/**', (route) => route.fulfill({ contentType: 'text/html', body: '<p>OAuth fixture; no external login.</p>' }));
  const popupPromise = page.waitForEvent('popup');
  await dialog.getByRole('button', { name: 'Continuer avec le fournisseur' }).click();
  const popup = await popupPromise; await popup.waitForURL('https://accounts.google.com/**');
  const authorization = new URL(popup.url());
  assert.equal(authorization.searchParams.get('code_challenge_method'), 'S256');
  assert(authorization.searchParams.get('scope')!.includes('gmail.compose'));
  assert(!authorization.searchParams.get('scope')!.includes('gmail.labels'));
  await popup.close(); await dialog.getByRole('button', { name: 'Continuer avec le fournisseur' }).waitFor({ state: 'visible' });
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' });
  const standard = page.locator('div.rounded-2xl').filter({ has: page.getByRole('heading', { name: 'IMAP / SMTP', exact: true }) }).last();
  await standard.getByRole('button', { name: 'Connecter', exact: true }).click();
  await page.getByRole('dialog').getByText('Serveur IMAP', { exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await withAccount(account, () => createConnector({ name: 'GitHub — fixture', kind: 'integration', config: { provider: 'github', account: { id: 'fixture', label: 'browser' }, permissions: ['read'], grantedScopes: ['read:user'] }, secrets: { access_token: 'never-in-browser' } }));
  await page.getByText('browser', { exact: true }).waitFor();
  assert(!(await page.content()).includes('never-in-browser'));
  page.once('dialog', (dialog) => dialog.accept());
  await page.getByRole('button', { name: 'Déconnecter', exact: true }).click();
  await page.getByText('browser', { exact: true }).waitFor({ state: 'hidden' });
  assert.equal((await withAccount(account, () => listConnectors('integration'))).length, 0);
  await promoteAdmin(account.email); await page.reload();
  await page.getByRole('button', { name: 'Connecteurs', exact: true }).click();
  await page.getByText('Applications OAuth du déploiement', { exact: true }).click();
  await page.getByText('Serveurs MCP', { exact: true }).waitFor();
  const microsoft = page.locator('div.flex.flex-wrap').filter({ has: page.locator('span', { hasText: /^microsoft$/ }) }).last();
  await microsoft.getByRole('button', { name: 'Configurer', exact: true }).click();
  await page.getByLabel('Client ID', { exact: true }).fill('ui-microsoft-client');
  await page.getByLabel('Client secret', { exact: true }).fill('ui-microsoft-secret');
  await page.getByRole('dialog').getByRole('button', { name: 'Enregistrer', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  const outlook = page.locator('div.rounded-2xl').filter({ has: page.getByRole('heading', { name: 'Outlook / Microsoft 365', exact: true }) }).last();
  await outlook.getByRole('button', { name: 'Connecter', exact: true }).click();
  await page.getByRole('dialog').getByRole('heading', { name: 'Connecter Outlook / Microsoft 365' }).waitFor();
  assert.equal(await page.getByRole('dialog').getByRole('checkbox').count(), 5);
  await page.keyboard.press('Escape');
  await page.screenshot({ path: process.env.OPENDOTS_UI_SCREENSHOT ?? '/tmp/opendots-connectors-ui.png', fullPage: true });
  await page.getByRole('button', { name: 'Se déconnecter', exact: true }).click();
  await page.getByRole('heading', { name: 'Connecte-toi à ton espace' }).waitFor();
  assert.equal((await context.request.get(`${origin}/api/agents`)).status(), 401);
  assert.deepEqual(errors, []);
  console.log('Chromium : inscription, confirmation du mot de passe, clé personnelle requise, catalogue, recherche, permissions, popup PKCE, IMAP, déconnexion native, configuration administrateur et logout vérifiés.');
} catch (error) {
  const page = browser.contexts()[0]?.pages().find((p) => p.url().startsWith(origin));
  if (page) { await page.screenshot({ path: '/tmp/opendots-ui-failure.png', fullPage: true }); console.error((await page.locator('body').innerText()).slice(-2500)); }
  throw error;
} finally {
  await browser.close(); await new Promise<void>((resolve) => server.close(() => resolve()));
  await closeAllDatabases(); await closeAuthStore(); await rm(dir, { recursive: true, force: true });
}
